function mathMarkup(formula){const tex=formulaTeX.get(formula);if(!tex)return escapeHTML(formula);return katex.renderToString(tex,{throwOnError:true,displayMode:false,output:'htmlAndMathml',strict:'error'});}
function inlineMath(text){return escapeHTML(text).replace(/([A-Za-zα-ωΑ-Ω])⃗|([ijk])̂|[îĵ]/gu,token=>{let tex;if(token==='î')tex=String.raw`\hat\imath`;else if(token==='ĵ')tex=String.raw`\hat\jmath`;else if(token.endsWith('⃗'))tex='\\vec '+token[0];else tex='\\hat '+token[0];return katex.renderToString(tex,{throwOnError:true,output:'htmlAndMathml'});});}
